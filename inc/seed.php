/**
 * Stand-in manuscript so the reader can be built and tested before the real book arrives.
 * Line prefixes: "# " chapter, "## " section, "? " reflection, "! " action point, "> " pull quote, "- " list item.
 */
function bk_seed_manuscript() {
	return <<<'BKMS'
# The Life You Are Already Building
## The quiet architecture
Every life has an architecture, whether or not anyone drew the plans. The hour you wake up, the first thing you reach for, the people you call back first, the room you spend most of your evening in. None of these feel like decisions. They feel like Tuesday.
But stand back far enough and the pattern is unmistakable. The small, repeated choices are load-bearing walls. They hold up the shape of your days, and your days hold up the shape of your years.
This book is not about tearing the house down. Most of us do not need a dramatic reinvention. We need to walk through the rooms we already live in, slowly, with the lights on, and ask a simple question in each one: did I choose this, or did it simply happen to me?
That question is gentler than it sounds. It does not accuse. It invites. And once you start asking it, you will notice how much of your life is waiting to be designed on purpose.
> The small, repeated choices are load-bearing walls. They hold up the shape of your days.
? Think of an ordinary weekday. Which part of it did you actively choose, and which part simply happened to you?
## Noticing your defaults
A default is whatever happens when you do nothing. Your phone has defaults. So does your calendar, your kitchen and your mood on a Monday morning.
Defaults are not bad. They are how a busy person survives. If you had to decide afresh how to brush your teeth each day, you would be exhausted by breakfast. The trouble is that most of our defaults were set by someone else, a long time ago, for a version of us that no longer exists.
The schedule you kept at university. The way your parents handled money. The habit you formed in a job you left three years ago. They are still running quietly in the background, like an app you forgot to close.
For the next few days, simply notice. You do not need to fix anything yet. Carry a small question with you: what am I doing right now because I chose it, and what am I doing because it is what I always do?
Write down three defaults you catch yourself in. Small ones are fine. Especially small ones.
- The first thing you look at when you wake up
- What you do in the ten minutes after you get home
- How you spend the last hour before you sleep
? Which of your defaults was set for a version of you that no longer exists?
## Choosing one room to start with
When people discover how much of their life runs on autopilot, the instinct is to change everything at once. New routine, new diet, new budget, new wardrobe, all starting Monday.
It rarely lasts. Not because you lack discipline, but because you are trying to renovate every room in the house while still living in it.
Pick one room. It might be literal, like your bedroom or your desk. It might be a part of your day, like your mornings. It might be a relationship, or the way you handle money on payday. Choose the one where a small change would make you feel most like yourself.
Then make one decision about it. Not ten. One. Something you can do this week, that you will notice when you have done it.
The rest of this book will walk through the rooms one at a time. For now, the goal is momentum, not perfection. A single intentional choice, kept, teaches you more about who you are becoming than a hundred resolutions abandoned.
> Pick one room. Make one decision. Keep it for a week.
! What is the one decision you will make about that room this week?
# Rooms That Shape You
## Your space is speaking
Walk into your home as if you were a guest. Not the version you tidy for visitors, the real one, on an ordinary evening.
What does it say about the person who lives there? Does it say rest, or does it say catching up? Does it say someone is building something here, or that someone is just getting through?
Spaces are never neutral. A chair facing the television asks you to watch. A desk buried under paper asks you to postpone. A bedside table with a book on it asks you to read, and one with a phone charger asks you to scroll.
We like to believe we are in charge of our rooms. More often, our rooms are quietly in charge of us. The good news is that this works both ways. Change what a room asks of you, and over time it will ask you to become someone different.
You do not need a renovation budget for this. You need attention, and a willingness to move a few things.
? If your main living space could speak, what would it say about the life you are living right now?
## Edit before you add
When a space feels wrong, the instinct is to buy something. A new lamp, a plant, a better organiser. Sometimes that helps. More often, the room does not need more. It needs less.
Editing is the quiet discipline of good design. You take things away until what remains has room to matter. A wall with one beautiful frame says more than a wall with twelve. A shelf with ten books you love invites you in, and a shelf with sixty you have never opened makes you feel behind.
Try this. Choose one surface in your home: a table, a counter, a shelf. Clear it completely. Then put back only what earns its place, either because you use it often or because it makes you feel something good when you see it.
Notice how the room changes. Notice how you change in it.
> A room does not always need more. Often it needs less, so that what remains can matter.
! Which one surface will you clear and reset this week?
## A corner for becoming
Every person who is growing needs a place where that growth happens. It does not have to be a room. A corner will do. A chair by a window, a small desk, even a particular end of the sofa.
What matters is that the place has one job. When you sit there, you read, or you write, or you think, or you pray. You do not answer emails there. You do not argue there. Over time your body learns the association, and simply sitting down becomes the first step of the habit.
Give the corner some care. Good light, a surface for a cup, somewhere to keep the book you are reading and a notebook. Perhaps one image on the wall that reminds you of who you are becoming.
Then protect it. Not with rules, but with use. Go there often, even for ten minutes. A place becomes meaningful because of what you repeatedly do in it.
? Where in your home could your corner for becoming live, and what would it need?
! Set up that corner this week, even in its simplest form, and spend ten minutes there.
# Feeding the Mind
## You become what you return to
There is an old idea that you become the average of the people you spend the most time with. It is worth extending. You also become the average of what you read, what you watch, what you listen to while you drive, and the conversations you replay at night.
The mind is not a container. It is more like soil. Whatever you plant there regularly will grow, whether it is an idea about your worth, a fear about money or a picture of the person you hope to be.
This is not a call to consume only serious things. Rest matters, and so does laughter. It is a call to notice the ratio. If almost everything you take in is designed to keep you scrolling, it should not surprise you when your thoughts feel scattered and borrowed.
Ask yourself honestly: of everything I took in this week, how much of it made me more?
> The mind is not a container. It is soil. Whatever you plant there regularly will grow.
? Of everything you read, watched or listened to this week, what actually made you more?
## Reading as a discipline, not a mood
Many people say they love reading, and then go months without finishing a book. The love is real. The practice is missing.
Waiting to be in the mood to read is like waiting to be in the mood to exercise. The mood usually arrives after you start, not before. So treat reading less like a hobby and more like a meal: something you do at a predictable time, in a predictable place, whether or not you feel inspired.
Start small. Ten pages a day is more than three thousand pages a year. That is ten or twelve books, and ten or twelve books can change the direction of a life.
Choose books that stretch you slightly beyond where you are. Not so far that you give up, not so close that nothing moves. And read with a pen, or with the highlighter in this reader. The books that change us are rarely the ones we read passively. They are the ones we argue with, underline and return to.
! Choose a daily reading time and place, and write them here.
## Conversations that stretch you
Books are one way to feed the mind. People are another, and often a faster one.
Think about the conversations in your week. How many of them left you with a new idea, a better question or a little more courage? How many simply passed the time?
There is nothing wrong with easy company. But growth needs at least a few relationships where you are not the most experienced person in the room. People who ask you what you are working on, and then ask a second, harder question. People who are living a little further down the road you want to travel.
These conversations rarely happen by accident. You have to ask for them. Invite someone for coffee and come with one real question. Join a room where people are building things. Offer something in return, because the best mentoring runs both ways.
You will be surprised how many people are glad to be asked.
> Growth needs at least a few rooms where you are not the most experienced person in them.
? Who is one person a little further down the road you want to travel?
! Reach out to that person this week with one real question.
BKMS;
}

/** Turn the manuscript into chapters of block markup. */
function bk_seed_parse( $text ) {
	$chapters = array();
	$cur      = null;
	$list     = array();
	$flush    = function () use ( &$cur, &$list ) {
		if ( $list && null !== $cur ) {
			$items = '';
			foreach ( $list as $li ) {
				$items .= '<!-- wp:list-item --><li>' . esc_html( $li ) . '</li><!-- /wp:list-item -->';
			}
			$cur['content'] .= "<!-- wp:list -->\n<ul class=\"wp-block-list\">" . $items . "</ul>\n<!-- /wp:list -->\n\n";
		}
		$list = array();
	};
	foreach ( preg_split( '/\R/', trim( $text ) ) as $line ) {
		$line = trim( $line );
		if ( '' === $line ) {
			continue;
		}
		if ( 0 === strpos( $line, '- ' ) ) {
			$list[] = substr( $line, 2 );
			continue;
		}
		$flush();
		if ( 0 === strpos( $line, '## ' ) ) {
			$cur['content'] .= "<!-- wp:heading -->\n<h2 class=\"wp-block-heading\">" . esc_html( substr( $line, 3 ) ) . "</h2>\n<!-- /wp:heading -->\n\n";
		} elseif ( 0 === strpos( $line, '# ' ) ) {
			if ( null !== $cur ) {
				$chapters[] = $cur;
			}
			$cur = array( 'title' => substr( $line, 2 ), 'content' => '' );
		} else {
			$map = array( '? ' => 'bk-reflect', '! ' => 'bk-action', '> ' => 'bk-quote' );
			$cls = '';
			$pre = substr( $line, 0, 2 );
			if ( isset( $map[ $pre ] ) ) {
				$cls  = $map[ $pre ];
				$line = substr( $line, 2 );
			}
			$attr  = $cls ? ' {"className":"' . $cls . '"}' : '';
			$class = $cls ? ' class="' . $cls . '"' : '';
			$cur['content'] .= '<!-- wp:paragraph' . $attr . " -->\n<p" . $class . '>' . esc_html( $line ) . "</p>\n<!-- /wp:paragraph -->\n\n";
		}
	}
	$flush();
	if ( null !== $cur ) {
		$chapters[] = $cur;
	}
	return $chapters;
}

/** Create or refresh the demo book. Safe to run more than once. */
function bk_seed_demo() {
	$slug = 'becoming-by-design';
	$book = get_page_by_path( $slug, OBJECT, 'bk_book' );
	$data = array(
		'post_type'    => 'bk_book',
		'post_status'  => 'publish',
		'post_name'    => $slug,
		'post_title'   => 'Becoming by Design',
		'post_excerpt' => 'A short, practical book about designing the rooms, habits and inputs that shape who you become. Read it one section at a time, and turn each idea into a decision.',
		'post_content' => '',
	);
	if ( $book ) {
		$data['ID'] = $book->ID;
		$book_id    = wp_update_post( $data );
	} else {
		$book_id = wp_insert_post( $data );
	}
	update_post_meta( $book_id, '_bk_author', 'Ann Uramu' );
	update_post_meta( $book_id, '_bk_standin', 1 );

	$existing = bk_book_chapters( $book_id );
	foreach ( bk_seed_parse( bk_seed_manuscript() ) as $n => $ch ) {
		$post = array(
			'post_type'    => 'bk_chapter',
			'post_status'  => 'publish',
			'post_title'   => $ch['title'],
			'post_content' => $ch['content'],
			'menu_order'   => $n + 1,
		);
		if ( isset( $existing[ $n ] ) ) {
			$post['ID'] = $existing[ $n ]->ID;
			$id         = wp_update_post( wp_slash( $post ) );
		} else {
			$id = wp_insert_post( wp_slash( $post ) );
		}
		update_post_meta( $id, '_bk_book', $book_id );
		update_post_meta( $id, '_bk_free', 0 === $n ? 1 : 0 );
	}
	return $book_id;
}
